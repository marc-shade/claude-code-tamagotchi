#!/usr/bin/env -S bun run
/**
 * Dynamic Skill Loading System
 *
 * Manages Claude Code's 20-skill limit by:
 * - Tracking active vs available skills
 * - Auto-loading contextually relevant skills
 * - Swapping skills based on usage patterns
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, renameSync, cpSync } from 'fs';
import { join } from 'path';

const HOME = process.env.HOME || '';
const ACTIVE_SKILLS_DIR = join(HOME, '.claude', 'skills');
const LIBRARY_SKILLS_DIR = join(HOME, '.claude', 'skills-library');
const SKILL_STATE_PATH = join(HOME, '.claude', 'skill-state.json');
const PET_STATE_PATH = join(HOME, '.claude', 'pets', 'claude-pet-state.json');

const MAX_ACTIVE_SKILLS = 20;

interface SkillState {
  name: string;
  active: boolean;
  usageCount: number;
  lastUsed: string;
  priority: number;
  autoGenerated: boolean;
  contextTags: string[];
}

interface SkillRegistry {
  skills: Record<string, SkillState>;
  activeCount: number;
  lastUpdate: string;
}

function getSkillRegistry(): SkillRegistry {
  if (!existsSync(SKILL_STATE_PATH)) {
    return {
      skills: {},
      activeCount: 0,
      lastUpdate: new Date().toISOString()
    };
  }
  return JSON.parse(readFileSync(SKILL_STATE_PATH, 'utf-8'));
}

function saveSkillRegistry(registry: SkillRegistry) {
  registry.lastUpdate = new Date().toISOString();
  writeFileSync(SKILL_STATE_PATH, JSON.stringify(registry, null, 2));
}

function scanSkills() {
  // Ensure directories exist
  if (!existsSync(ACTIVE_SKILLS_DIR)) mkdirSync(ACTIVE_SKILLS_DIR, { recursive: true });
  if (!existsSync(LIBRARY_SKILLS_DIR)) mkdirSync(LIBRARY_SKILLS_DIR, { recursive: true });

  const registry = getSkillRegistry();
  const activeSkills = existsSync(ACTIVE_SKILLS_DIR) ? readdirSync(ACTIVE_SKILLS_DIR) : [];
  const librarySkills = existsSync(LIBRARY_SKILLS_DIR) ? readdirSync(LIBRARY_SKILLS_DIR) : [];

  // Update registry with discovered skills
  for (const skillName of activeSkills) {
    if (!registry.skills[skillName]) {
      registry.skills[skillName] = {
        name: skillName,
        active: true,
        usageCount: 0,
        lastUsed: new Date().toISOString(),
        priority: 5,
        autoGenerated: false,
        contextTags: []
      };
    } else {
      registry.skills[skillName].active = true;
    }
  }

  for (const skillName of librarySkills) {
    if (!registry.skills[skillName]) {
      registry.skills[skillName] = {
        name: skillName,
        active: false,
        usageCount: 0,
        lastUsed: new Date().toISOString(),
        priority: 5,
        autoGenerated: false,
        contextTags: []
      };
    } else {
      registry.skills[skillName].active = false;
    }
  }

  registry.activeCount = activeSkills.length;
  saveSkillRegistry(registry);

  return registry;
}

function loadSkill(skillName: string): boolean {
  const registry = scanSkills();
  const skill = registry.skills[skillName];

  if (!skill) {
    console.error(`Skill '${skillName}' not found`);
    return false;
  }

  if (skill.active) {
    console.log(`Skill '${skillName}' is already active`);
    return true;
  }

  if (registry.activeCount >= MAX_ACTIVE_SKILLS) {
    console.error(`Cannot load skill: ${registry.activeCount}/${MAX_ACTIVE_SKILLS} skills active`);
    console.log('Unload a skill first or use /skill-load --auto for intelligent swapping');
    return false;
  }

  // Move from library to active
  const libPath = join(LIBRARY_SKILLS_DIR, skillName);
  const activePath = join(ACTIVE_SKILLS_DIR, skillName);

  if (!existsSync(libPath)) {
    console.error(`Skill directory not found: ${libPath}`);
    return false;
  }

  renameSync(libPath, activePath);

  // Update registry
  skill.active = true;
  skill.lastUsed = new Date().toISOString();
  registry.activeCount++;
  saveSkillRegistry(registry);

  console.log(`✓ Loaded skill: ${skillName}`);
  console.log(`  Active: ${registry.activeCount}/${MAX_ACTIVE_SKILLS}`);

  return true;
}

function unloadSkill(skillName: string): boolean {
  const registry = scanSkills();
  const skill = registry.skills[skillName];

  if (!skill) {
    console.error(`Skill '${skillName}' not found`);
    return false;
  }

  if (!skill.active) {
    console.log(`Skill '${skillName}' is already unloaded`);
    return true;
  }

  // Move from active to library
  const activePath = join(ACTIVE_SKILLS_DIR, skillName);
  const libPath = join(LIBRARY_SKILLS_DIR, skillName);

  if (!existsSync(activePath)) {
    console.error(`Skill directory not found: ${activePath}`);
    return false;
  }

  renameSync(activePath, libPath);

  // Update registry
  skill.active = false;
  registry.activeCount--;
  saveSkillRegistry(registry);

  console.log(`✓ Unloaded skill: ${skillName}`);
  console.log(`  Active: ${registry.activeCount}/${MAX_ACTIVE_SKILLS}`);

  return true;
}

function autoLoadSkills() {
  const registry = scanSkills();

  // Find inactive skills that should be loaded
  const inactiveSkills = Object.values(registry.skills)
    .filter(s => !s.active)
    .sort((a, b) => {
      // Sort by priority (higher first), then usage count, then recency
      if (a.priority !== b.priority) return b.priority - a.priority;
      if (a.usageCount !== b.usageCount) return b.usageCount - a.usageCount;
      return new Date(b.lastUsed).getTime() - new Date(a.lastUsed).getTime();
    });

  // Find active skills that could be unloaded
  const activeSkills = Object.values(registry.skills)
    .filter(s => s.active)
    .sort((a, b) => {
      // Sort by priority (lower first), then usage count (lower first)
      if (a.priority !== b.priority) return a.priority - b.priority;
      if (a.usageCount !== b.usageCount) return a.usageCount - b.usageCount;
      return new Date(a.lastUsed).getTime() - new Date(b.lastUsed).getTime();
    });

  const slotsAvailable = MAX_ACTIVE_SKILLS - registry.activeCount;
  let loaded = 0;

  console.log(`\n🔄 Auto-loading contextually relevant skills...\n`);

  // Load high-priority inactive skills
  for (const skill of inactiveSkills) {
    if (loaded >= slotsAvailable) {
      // Need to unload low-priority active skill first
      if (activeSkills.length > 0 && activeSkills[0].priority < skill.priority) {
        const toUnload = activeSkills.shift()!;
        console.log(`  Unloading low-priority: ${toUnload.name}`);
        unloadSkill(toUnload.name);
      } else {
        break;
      }
    }

    console.log(`  Loading: ${skill.name} (priority: ${skill.priority})`);
    if (loadSkill(skill.name)) {
      loaded++;
    }
  }

  console.log(`\n✓ Auto-loaded ${loaded} skills`);
  console.log(`  Active: ${registry.activeCount}/${MAX_ACTIVE_SKILLS}`);
}

function listSkills() {
  const registry = scanSkills();

  console.log(`\n📚 Skill Registry (${registry.activeCount}/${MAX_ACTIVE_SKILLS} active)\n`);

  const activeSkills = Object.values(registry.skills).filter(s => s.active);
  const inactiveSkills = Object.values(registry.skills).filter(s => !s.active);

  if (activeSkills.length > 0) {
    console.log('ACTIVE SKILLS:');
    activeSkills.forEach(skill => {
      const autoGen = skill.autoGenerated ? '[AUTO]' : '';
      console.log(`  ✓ ${skill.name} ${autoGen}`);
      console.log(`    Priority: ${skill.priority} | Used: ${skill.usageCount} times | Last: ${new Date(skill.lastUsed).toLocaleDateString()}`);
    });
    console.log('');
  }

  if (inactiveSkills.length > 0) {
    console.log('AVAILABLE SKILLS:');
    inactiveSkills.forEach(skill => {
      const autoGen = skill.autoGenerated ? '[AUTO]' : '';
      console.log(`  ○ ${skill.name} ${autoGen}`);
      console.log(`    Priority: ${skill.priority} | Used: ${skill.usageCount} times | Last: ${new Date(skill.lastUsed).toLocaleDateString()}`);
    });
    console.log('');
  }

  if (registry.activeCount >= MAX_ACTIVE_SKILLS) {
    console.log('⚠️  Skill limit reached. Unload skills to add new ones.');
  } else {
    console.log(`✓ ${MAX_ACTIVE_SKILLS - registry.activeCount} slots available`);
  }
}

function main() {
  const args = process.argv.slice(2);

  if (args.length === 0 || args[0] === 'list') {
    listSkills();
    return;
  }

  const command = args[0];

  switch (command) {
    case '--auto':
    case '--context':
      autoLoadSkills();
      break;

    case '--unload':
      if (args[1]) {
        unloadSkill(args[1]);
      } else {
        console.error('Usage: /skill-load --unload <skill-name>');
      }
      break;

    case '--swap':
      if (args[1] && args[2]) {
        unloadSkill(args[1]);
        loadSkill(args[2]);
      } else {
        console.error('Usage: /skill-load --swap <out> <in>');
      }
      break;

    default:
      // Load specific skill
      loadSkill(command);
      break;
  }
}

main();
