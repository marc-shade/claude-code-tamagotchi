#!/bin/bash
# Claude Code Tamagotchi - Adaptive Multi-System Setup
# Detects system capabilities and configures integration accordingly

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

echo "🐾 Claude Code Tamagotchi - Adaptive Setup"
echo "==========================================="
echo ""

# Step 1: Detect system capabilities
echo "📊 Detecting system capabilities..."
bash "$SCRIPT_DIR/scripts/detect-system.sh"

if [ ! -f "$HOME/.claude/tamagotchi-system-info.json" ]; then
    echo "❌ System detection failed. Please check scripts/detect-system.sh"
    exit 1
fi

echo "✅ System detection complete"
echo ""

# Load detected capabilities
WATCHDOG_AVAILABLE=$(cat "$HOME/.claude/tamagotchi-system-info.json" | grep -o '"watchdog_available":[^,}]*' | cut -d':' -f2 | tr -d ' ')
MEMORY_AVAILABLE=$(cat "$HOME/.claude/tamagotchi-system-info.json" | grep -o '"enhanced_memory":[^,}]*' | cut -d':' -f2 | tr -d ' ')
GROQ_AVAILABLE=$(cat "$HOME/.claude/tamagotchi-system-info.json" | grep -o '"groq":[^,}]*' | cut -d':' -f2 | tr -d ' ')

echo "System Capabilities:"
echo "  Watchdog: $WATCHDOG_AVAILABLE"
echo "  Enhanced Memory: $MEMORY_AVAILABLE"
echo "  Groq API: $GROQ_AVAILABLE"
echo ""

# Step 2: Install dependencies
echo "📦 Installing dependencies..."
if ! command -v bun &> /dev/null; then
    echo "⚠️  Bun not found. Installing..."
    curl -fsSL https://bun.sh/install | bash
fi

cd "$SCRIPT_DIR"
bun install
echo "✅ Dependencies installed"
echo ""

# Step 3: Install slash commands
echo "💬 Installing slash commands..."
mkdir -p "$HOME/.claude/commands"

for cmd in pet-pet pet-feed pet-play pet-clean pet-sleep pet-wake pet-stats pet-name pet-reset pet-help; do
    if [ -f "$SCRIPT_DIR/commands/${cmd}.md" ]; then
        cp "$SCRIPT_DIR/commands/${cmd}.md" "$HOME/.claude/commands/"
        echo "  ✓ ${cmd}"
    fi
done

echo "✅ Slash commands installed"
echo ""

# Step 4: Install hooks
echo "🪝 Installing workflow hooks..."
mkdir -p "$HOME/.claude/hooks"

cp "$SCRIPT_DIR/hooks/post-tool-use.sh" "$HOME/.claude/hooks/"
chmod +x "$HOME/.claude/hooks/post-tool-use.sh"

echo "$SCRIPT_DIR" > "$HOME/.claude/tamagotchi-path.txt"

echo "✅ Hooks installed"
echo ""

# Step 5: Configure settings.json
echo "⚙️  Configuring Claude Code settings..."

SETTINGS_FILE="$HOME/.claude/settings.json"

# Backup existing settings
if [ -f "$SETTINGS_FILE" ]; then
    cp "$SETTINGS_FILE" "${SETTINGS_FILE}.backup-$(date +%Y%m%d-%H%M%S)"
fi

# Create settings if it doesn't exist
if [ ! -f "$SETTINGS_FILE" ]; then
    echo '{}' > "$SETTINGS_FILE"
fi

# Configure statusLine
if [ "$WATCHDOG_AVAILABLE" = "true" ]; then
    STATUSLINE_COMMAND="cd '$SCRIPT_DIR' && bun run --silent src/index.ts"
else
    STATUSLINE_COMMAND="cd '$SCRIPT_DIR' && bun run --silent src/index.ts"
fi

# Use jq if available, otherwise use sed
if command -v jq &> /dev/null; then
    TEMP_FILE=$(mktemp)
    jq --arg cmd "$STATUSLINE_COMMAND" '.statusLine = {type: "command", command: $cmd}' "$SETTINGS_FILE" > "$TEMP_FILE"
    mv "$TEMP_FILE" "$SETTINGS_FILE"
else
    # Fallback to manual JSON editing
    echo "⚠️  jq not found, manual settings update required"
    echo "Please add to $SETTINGS_FILE:"
    echo '{'
    echo '  "statusLine": {'
    echo '    "type": "command",'
    echo "    \"command\": \"$STATUSLINE_COMMAND\""
    echo '  }'
    echo '}'
fi

# Configure hooks
if command -v jq &> /dev/null; then
    TEMP_FILE=$(mktemp)
    jq '.hooks.PostToolUse = [{matcher: "*", hooks: [{type: "command", command: "bash $HOME/.claude/hooks/post-tool-use.sh", timeout: 5}]}]' "$SETTINGS_FILE" > "$TEMP_FILE"
    mv "$TEMP_FILE" "$SETTINGS_FILE"
fi

echo "✅ Settings configured"
echo ""

# Step 6: Generate environment file
echo "🌍 Generating environment configuration..."

ENV_FILE="$HOME/.tamagotchi.env"

cat > "$ENV_FILE" << EOF
# Claude Code Tamagotchi Environment Configuration
# Generated by adaptive-setup.sh on $(date)

# Core pet settings
export PET_STATE_FILE="\$HOME/.claude/pets/pet-state.json"

# Feedback system
export PET_FEEDBACK_ENABLED=true
EOF

if [ "$GROQ_AVAILABLE" = "true" ]; then
    cat >> "$ENV_FILE" << EOF
export GROQ_API_KEY="${GROQ_API_KEY}"
EOF
fi

if [ "$WATCHDOG_AVAILABLE" = "true" ]; then
    WATCHDOG_PATH=$(cat "$HOME/.claude/tamagotchi-system-info.json" | grep -o '"watchdog_path":"[^"]*"' | cut -d'"' -f4)
    cat >> "$ENV_FILE" << EOF

# Watchdog integration
export PET_WATCHDOG_ENABLED=true
export PET_WATCHDOG_DB="\$HOME/.claude/watchdog/watchdog.db"
export PET_WATCHDOG_PATH="$WATCHDOG_PATH"
EOF
fi

if [ "$MEMORY_AVAILABLE" = "true" ]; then
    cat >> "$ENV_FILE" << EOF

# Enhanced memory integration
export PET_MEMORY_ENABLED=true
export PET_MEMORY_DB="\$HOME/.enhanced-memory/graph.db"
EOF
fi

echo "✅ Environment file created: $ENV_FILE"
echo ""

# Step 7: Create pet state directory
mkdir -p "$HOME/.claude/pets"

echo "==========================================="
echo "✅ Setup complete!"
echo ""
echo "Next steps:"
echo "1. Add to your shell profile (~/.zshrc or ~/.bashrc):"
echo "   source $ENV_FILE"
echo ""
echo "2. Restart Claude Code to activate the status line"
echo ""
echo "3. Test with slash commands:"
echo "   /pet-help"
echo "   /pet-stats"
echo "   /pet-feed pizza"
echo ""
echo "Your pet will be automatically cared for as you work!"
echo "==========================================="
